const DEFAULT_KEY = "fjolbyliCap";

/** Get a fully-sorted series for a property-type key. */
export function hmsSeries(key: string): HMSSeries {
  const s = SERIES[key] ?? SERIES[DEFAULT_KEY]!;
  return {
    ...s,
    points: [...s.points].sort((a, b) => a.month.localeCompare(b.month)),
  };
}

/** Linearly interpolated index for a property-type key at a month. */
export function hmsIndexForMonth(key: string, month: string): number {
  const pts = SERIES[key] ?? SERIES[DEFAULT_KEY]!;
  const sorted = [...pts.points].sort((a, b) => a.month.localeCompare(b.month));
  const byMonth = new Map(sorted.map((d) => [d.month, d.index]));
  const first = sorted[0]!;
  const last = sorted[sorted.length - 1]!;
  if (month <= first.month) return first.index;
  if (month >= last.month) return last.index;
  const exact = byMonth.get(month);
  if (exact !== undefined) return exact;
  for (let i = 1; i < sorted.length; i++) {
    const a = sorted[i - 1]!;
    const b = sorted[i]!;
    if (month >= a.month && month <= b.month) {
      const span = monthDiff(a.month, b.month);
      const pos = monthDiff(a.month, month);
      return a.index + ((b.index - a.index) * pos) / span;
    }
  }
  return last.index;
}

/** Months between a month and a series' latest data month (>0 = data is old). */
export function hmsAgeMonths(key: string, month: string): number {
  const s = SERIES[key] ?? SERIES[DEFAULT_KEY]!;
  const last = [...s.points].sort((a, b) => a.month.localeCompare(b.month)).pop()!;
  return monthDiff(last.month, month);
}

function monthDiff(a: string, b: string): number {
  const [ay, am] = a.split("-").map(Number);
  const [by, bm] = b.split("-").map(Number);
  return (by! - ay!) * 12 + (bm! - am!);
}
