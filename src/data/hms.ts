/**
 * HMS íbúðaverðsvísitölur (nominal).
 *
 * Monthly index series by property type, captured from hms.is "Vísitölur
 * íbúða- og leiguverðs" (kaupvisitala.csv). hms.is is bot-gated, so the
 * series is a curated snapshot of the CSV — see README for how to refresh.
 *
 * Every series spans the same months (2020-01 → 2026-07, published Aug 2026).
 * Public market data (not personal) — safe to ship. The chart uses a chosen
 * series to derive the property-value curve instead of a pure growth guess.
 */

export interface HMSDataPoint {
  month: string; // "YYYY-MM"
  index: number;
}

export interface HMSSeries {
  /** Stable key (matches the CSV column name). */
  key: string;
  /** Icelandic label for the dropdown. */
  label: string;
  /** Short description (property type + region). */
  description: string;
  /** The latest monthly value. */
  lastIndex: number;
  /** ISO date the latest value was published. */
  publishedAt: string;
  points: HMSDataPoint[];
}

